function rnd(seed) { return () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; }; }
const pk = (a, r = Math.random) => a[Math.floor(r() * a.length)];
const two = (a, r) => { const i = Math.floor(r() * a.length), j = (i + 1 + Math.floor(r() * (a.length - 1))) % a.length; return a[i] + ', ' + a[j]; };
function pickLv() { let t = Math.random() * 100, s = 0; for (let i = 0; i < 4; i++) { s += LEVELS[i].w; if (t < s) return i; } return 1; }

function makeReading(id) {
  const S = STATIONS.find((x) => x.id === id), o = { th: S.th, zh: S.zh, lv: -1, lines: [] };
  if (TEXT[id]) {
    const lv = pickLv(); o.lv = lv;
    o.lines = [pk(TEXT[id][lv]), 'สีมงคล: ' + pk(COLORS) + '   เลขมงคล: ' + (1 + Math.floor(Math.random() * 9))];
  } else if (id === 'qian') {
    const lv = pickLv(); o.lv = lv;
    o.lines = [...COUPLET[lv].slice().sort(() => Math.random() - 0.5).slice(0, 2), 'เซียมซีใบที่ ' + (1 + Math.floor(Math.random() * 100))];
  } else if (id === 'buei') {
    const r = Math.random(); o.lines = [BUEI[r < 0.5 ? 0 : r < 0.75 ? 1 : 2]];
  } else if (id === 'almanac') {
    const d = new Date(), r = rnd(d.getFullYear() * 400 + d.getMonth() * 31 + d.getDate());
    o.lines = ['宜 เหมาะกับ: ' + two(YI, r), '忌 ควรเลี่ยง: ' + two(JI, r), 'ทิศมงคลวันนี้: ' + pk(DIR, r)];
  } else o.lines = [pk(BLESS[id])];
  return o;
}
