const blessingHistory = {};

function pickBlessing(rarityIndex){
  const pool = RAR[rarityIndex]?.t || [];

  if(!pool.length) return '';

  if(!blessingHistory[rarityIndex]){
    blessingHistory[rarityIndex] = [];
  }

  let used = blessingHistory[rarityIndex];

  // ใช้ครบทุกประโยคแล้ว เริ่มรอบใหม่
  if(used.length >= pool.length){
    used = [];
    blessingHistory[rarityIndex] = used;
  }

  // เลือกเฉพาะประโยคที่ยังไม่เคยใช้
  const available = pool
    .map((text,index)=>({text,index}))
    .filter(item=>!used.includes(item.index));

  const selected =
    available[Math.floor(Math.random()*available.length)];

  used.push(selected.index);

  return selected.text;
}

